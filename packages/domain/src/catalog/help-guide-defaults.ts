/**
 * The in-bot guide: every section, in the order `/help` lists them, with the
 * text it shows until somebody edits it in the panel (migration 0063).
 *
 * ── Why the text is code and the edits are rows ─────────────────────────────
 *
 * The same split as `SETTING_DEFAULTS`: the code says what a section is and
 * what it says by default, and `help_guide` holds only what an operator
 * changed. A release that corrects a default reaches every section nobody
 * edited; an edited one keeps its operator's words until they reset it.
 *
 * ── Why the numbers are placeholders ────────────────────────────────────────
 *
 * Every price, penalty and window here is a setting an operator can move from
 * the panel without a deploy. A guide that spelled out «۲۰ سکه» would be
 * contradicted by the bot the day somebody changed it, and nobody would think
 * to edit the guide as well. `{{economy.event_join_coins}}` is filled from the
 * live value each time the page is drawn (`renderGuideText`), so the guide and
 * the ledger cannot disagree. `{{key|abs}}` drops the sign of a negative
 * setting, for the review ratings that lower a score.
 *
 * What is *not* a placeholder is fixed in code: the 24- and 3-hour boundaries
 * of the cancellation buckets, the 180-day message retention, the button
 * labels. Those change with a release, and a release updates this file.
 *
 * ── The voice ───────────────────────────────────────────────────────────────
 *
 * Written from the channel posts the operator approved (2026-09-26), in their
 * spoken register, and checked against the code of v0.20: the join charge is
 * a price refunded when you do not get in, not a deposit; the event fee is
 * quoted as one sum, never split; a full event's button is the waiting list's;
 * and there is no «سایر» with a name of your own.
 */
